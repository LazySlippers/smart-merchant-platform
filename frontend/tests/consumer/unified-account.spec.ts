  await page.getByRole('button',{name:'自愿加入商家会员',exact:true}).click()
  await page.getByLabel('原商家密码', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: '验证并关联', exact: true }).click()
  await expect(page.getByText('原商家密码错误', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('consumer.accounts.v2') || '[]')[0].accessToken)).toBe('global-owner')
  await page.getByLabel('原商家密码', { exact: true }).fill('Original!12345')
  await page.getByRole('button', { name: '验证并关联', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '消费者登录' })).toHaveCount(0)
