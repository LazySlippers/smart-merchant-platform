import { test, expect, type Page } from '@playwright/test'

async function fixture(page: Page, existing = false) {
  const calls: { path: string; token: string; body: any }[] = []
  const bound = new Set(existing ? ['61', '62', '63'] : [])
  let failed = true
  await page.addInitScript(() => {
    localStorage.setItem('marketplace.visits', JSON.stringify([{ tenantId: '99', id: '991', storeName: '其他账号逛过的店', address: '' }]))
    sessionStorage.setItem('consumer.session:99', JSON.stringify('stale-other-owner'))
  })
  const store = (tenant: string) => ({ id: `${tenant}1`, tenantId: tenant, storeName: `${tenant}号邻里店`, address: '邻里路1号', businessHours: '09:00–21:00', city: '杭州', district: '西湖', coverUrl: '', pickupEnabled: true, shippingEnabled: false, distanceKm: null })
  const order = (id: number, tenant: string) => ({ id: String(id), orderNo: `订单${id}`, storeId: `${tenant}1`, status: 'PENDING_PAYMENT', totalQuantity: 1, payableAmountCents: 1000, totalAmountCents: 1000, items: [{ productName: `商品${id}`, skuName: '标准', quantity: 1 }], customerMobile: '13800138000' })
  await page.route('**/api/consumer/v1/**', async route => {
    const req = route.request(), url = new URL(req.url()), path = url.pathname.replace('/api/consumer/v1', '')
    const token = req.headers().authorization || '', body = req.method() === 'POST' ? req.postDataJSON() : undefined
    calls.push({ path, token, body })
    const send = (data: any, status = 200) => route.fulfill({ status, json: data })
    if (path === '/auth/account/login' || path === '/auth/account/register') return send({ accessToken: body.mobile==='13900139000'?'global-second':'global-owner', expiresIn: 7200, mobile: body.mobile, displayName: body.mobile==='13900139000'?'阿新':'小邻' })
    if (path === '/auth/account/memberships') return send([...(token==='Bearer global-second'?[]:bound)].map(tenantId => ({ tenantId, memberId: `${tenantId}01`, memberName: '小邻', status: 'ACTIVE' })))
    if (path === '/auth/account/activate' || path === '/auth/account/logout') return send({verified:true})
    if (path === '/auth/account/privacy') return send({historyEnabled:true})
    if (path === '/auth/account/addresses') return send([])
    if (path.startsWith('/auth/account/history')) return send([])
    if (path === '/auth/account/me' || path === '/auth/account/password') return send({ changed: true })
    if (path === '/auth/account/enter') {
      if (body.tenantId === '63' && failed) return send({ detail: '品牌暂不可用' }, 404)
      bound.add(body.tenantId)
      return send({ accessToken: `member-${body.tenantId}`, expiresIn: 7200, member: true })
    }
    if (path === '/catalog/stores') return send(['61', '62'].map(store))
    if (path.endsWith('/brand')) return send({ displayName: `${path.split('/')[3]}号邻里店`, contactPhone: '' })
    if (path.endsWith('/products')) return send({ store: store(path.split('/')[3]), products: [] })
    if (path.endsWith('/fulfillment')) return send({ pickupEnabled: true, shippingEnabled: false, pickupOnlySkus: [], excludedProvinces: [] })
    if (path.startsWith('/catalog/tenants/') && path.endsWith('/stores')) return send([store(path.split('/')[3])])
    if (path === '/wallet') return send({ id: '6101', mobile: '13800138000', memberName: '小邻', availablePoints: 0, storedValueCents: 0 })
    if (path === '/orders/capabilities') return send({ simulatedPaymentEnabled: false })
    if (path === '/profile') return send({ memberName: '小邻', notifications: true })
    if (path === '/orders') {
      const tenant = token.replace('Bearer member-', '')
      return send(url.searchParams.get('page') === '0'
        ? tenant === '61' ? Array.from({ length: 20 }, (_, i) => order(1000 - i, tenant)) : [order(2000 + Number(tenant), tenant)]
        : [order(800, tenant)])
    }
    if (path.startsWith('/orders/')) return send(order(Number(path.split('/')[2]), '62'))
    return send([])
  })
  return { calls, bound, recover: () => { failed = false } }
}
