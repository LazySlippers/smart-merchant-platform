test('member, address, coupons and responsive screens persist locally', async ({ page }) => {
  await page.goto('/?preview=1#addresses')
  await page.getByRole('button', { name: '新增收货地址' }).click()
  await page.getByLabel('联系人', { exact: true }).fill('测试用户')
  await page.getByLabel('手机号', { exact: true }).fill('13800000001')
  await page.getByLabel('详细地址').fill('杭州市测试路 100 号')
  await page.getByRole('button', { name: '保存地址', exact: true }).click()
  await page.reload()
  await expect(page.getByText('杭州市测试路 100 号', { exact: true })).toBeVisible()
  await page.goto('/?preview=1#coupons')
  await page.getByRole('button', { name: '领取', exact: true }).click()
  await expect(page.getByRole('button', { name: '已领取', exact: true })).toBeDisabled()
  await page.goto('/?preview=1#points')
  await page.getByRole('button', { name: '立即兑换', exact: true }).first().click()
  await expect(page.locator('.points-hero strong')).toHaveText('48')
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    for (const route of ['home','shop','me','stores','orders','gift','help','balance']) {
      await page.goto('/?preview=1#' + route)
      await expect(page.locator('main')).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${route} width ${width}`).toBe(true)
      if (width === 390 && ['shop','me'].includes(route)) await page.screenshot({ path: `apps/consumer-web/qa/prototype-${route}.png`, fullPage: true })
    }
  }
})
