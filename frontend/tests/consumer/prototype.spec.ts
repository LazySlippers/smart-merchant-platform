import { test, expect } from '@playwright/test'

test('store switching keeps independent carts and delivery totals', async ({ page }) => {
  await page.goto('/?preview=1#shop')
  await page.getByRole('button', { name: '选规格 云顶抹茶拿铁', exact: true }).click()
  await page.getByRole('button', { name: '加入购物袋 · ¥22' }).click()
  await page.locator('.shop-store > button').click()
  await page.locator('.store-choice').nth(1).getByRole('button').click()
  await page.getByRole('button', { name: '确认切换门店' }).click()
  await expect(page.getByRole('button', { name: '去结算', exact: true })).toBeDisabled()
  await page.locator('.shop-store > button').click()
  await page.locator('.store-choice').first().getByRole('button').click()
  await expect(page.locator('.bag-summary')).toContainText('¥22')
  await page.getByRole('button', { name: '外送', exact: true }).click()
  await page.getByRole('button', { name: '去结算', exact: true }).click()
  await expect(page.locator('.checkout-bottom')).toContainText('¥22')
  await expect(page.locator('.receipt-row').filter({ hasText: '配送费' })).toContainText('¥6')
})

